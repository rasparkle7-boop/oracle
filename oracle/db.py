from .config import settings

_INIT_LOCK = threading.Lock()
_INITIALISED = False


class _PostgresConnection:
    """Small psycopg adapter for the existing SQLite-style application API."""
    def __init__(self, raw):
        self.raw = raw

    @staticmethod
    def _translate(sql):
        # Translate ? placeholders without touching quoted SQL strings.
        # SQLite JSON helpers are used only for scalar paths in fixture listings.
        sql = re.sub(
            r"json_extract\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*,\s*'\$\.([A-Za-z_][A-Za-z0-9_]*)'\s*\)",
            lambda m: (
                f"({m.group(1)}::jsonb -> '{m.group(2)}')::text"
                if m.group(2) == "flags"
                else f"({m.group(1)}::jsonb ->> '{m.group(2)}')"
            ),
            sql,
            flags=re.IGNORECASE,
        )
        out = []
        quote = None
        i = 0
        while i < len(sql):
            ch = sql[i]
            if quote:
                out.append(ch)
                if ch == quote:
                    if i + 1 < len(sql) and sql[i + 1] == quote:
                        out.append(sql[i + 1])
                        i += 1
                    else:
                        quote = None
                elif ch == "\\" and i + 1 < len(sql):
                    out.append(sql[i + 1])
                    i += 1
            elif ch in ("'", '"'):
                quote = ch
                out.append(ch)
            elif ch == "?":
                out.append("%s")
            else:
                out.append(ch)
            i += 1
        return "".join(out)

    def execute(self, sql, params=()):
        return self.raw.execute(self._translate(sql), tuple(params))

    def executescript(self, sql):
        return self.raw.execute(sql, prepare=False)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def _postgres_schema(schema):
    schema = re.sub(r"(?im)^\s*PRAGMA\s+[^;]+;\s*", "", schema)
    schema = schema.replace(
        "id INTEGER PRIMARY KEY AUTOINCREMENT",
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    # PostgreSQL primary keys cannot contain nullable provider/line columns.
    schema = schema.replace(
        "PRIMARY KEY (fixture_id, source, provider, market, selection, line)",
        "UNIQUE NULLS NOT DISTINCT (fixture_id, source, provider, market, selection, line)"
    )
    schema = schema.replace(
        "idx_history_teams ONhistorical_results",
        "idx_history_teams ON historical_results"
    )
    return schema


def utcnow() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def new_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:12]}"


def connect(path: Path | None = None):
    database_url = __import__("os").getenv("DATABASE_URL", "").strip()
    if database_url and path is None:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Install dependencies: pip install -r requirements.txt") from exc
        raw = psycopg.connect(database_url, row_factory=dict_row, connect_timeout=20)
        return _PostgresConnection(raw)

    path = path or settings.db_path
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path), timeout=30, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode = WAL")
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA busy_timeout = 30000")
    return conn


@contextmanager
def db() -> Iterator[sqlite3.Connection]:
    conn = connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    global _INITIALISED
    with _INIT_LOCK:
        if _INITIALISED:
            return
        schema = (Path(__file__).parent / "schema.sql").read_text(encoding="utf-8")
        if __import__("os").getenv("DATABASE_URL", "").strip():
            with db() as conn:
                table_names = re.findall(
                    r"(?im)^\s*CREATE TABLE IF NOT EXISTS\s+(\w+)", schema
                )
                placeholders = ",".join("?" for _ in table_names)
                present = scalar(
                    conn,
                    "SELECT count(*) FROM information_schema.tables "
                    f"WHERE table_schema=current_schema() AND table_name IN ({placeholders})",
                    table_names,
                    0,
                )
                # Avoid replaying index/table DDL on every service start. A running
                # sync writes these tables continuously and can hold deployment locks.
                if present < len(table_names):
                    conn.executescript(_postgres_schema(schema))

                columns = rows(
                    conn,
                    "SELECT table_name, column_name FROM information_schema.columns "
                    "WHERE table_schema=current_schema() AND ((table_name='settlements' "
                    "AND column_name='pick_prob') OR (table_name='prediction_history' "
                    "AND column_name='lineups_fingerprint'))",
                )
                present_columns = {(r["table_name"], r["column_name"]) for r in columns}
                if ("settlements", "pick_prob") not in present_columns:
                    conn.execute("ALTER TABLE settlements ADD COLUMN pick_prob REAL")
                if ("prediction_history", "lineups_fingerprint") not in present_columns:
                    conn.execute(
                        "ALTER TABLE prediction_history ADD COLUMN lineups_fingerprint TEXT DEFAULT ''"
                    )
        else:
            with db() as conn:
                conn.executescript(schema)
                cols = {r[1] for r in conn.execute("PRAGMA table_info(settlements)")}
                if "pick_prob" not in cols:
                    conn.execute("ALTER TABLE settlements ADD COLUMN pick_prob REAL")
                hcols = {r[1] for r in conn.execute("PRAGMA table_info(prediction_history)")}
                if "lineups_fingerprint" not in hcols:
                    conn.execute("ALTER TABLE prediction_history ADD COLUMN lineups_fingerprint TEXT DEFAULT ''")
        _INITIALISED = True


def json_dumps(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), default=str)


def json_loads(value: Any, default: Any = None) -> Any:
    if value is None or value == "":
        return default
    if isinstance(value, (dict, list)):
        return value
    try:
        return json.loads(value)
    except Exception:
        return default


def rows(conn: sqlite3.Connection, sql: str, params: Iterable[Any] = ()) -> list[dict]:
    return [dict(r) for r in conn.execute(sql, tuple(params)).fetchall()]


def row(conn: sqlite3.Connection, sql: str, params: Iterable[Any] = ()) -> dict | None:
    r = conn.execute(sql, tuple(params)).fetchone()
    return dict(r) if r else None


def scalar(conn: sqlite3.Connection, sql: str, params: Iterable[Any] = (), default: Any = None) -> Any:
    r = conn.execute(sql, tuple(params)).fetchone()
    return (next(iter(r.values())) if isinstance(r, dict) else r[0]) if r else default


def set_state(key: str, value: Any, conn: sqlite3.Connection | None = None) -> None:
    payload = json_dumps(value) if not isinstance(value, str) else value
    own = conn is None
    conn = conn or connect()
    try:
        conn.execute(
            "INSERT INTO sync_state(key, value, updated_at) VALUES(?,?,?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
            (key, payload, utcnow()),
        )
        if own:
            conn.commit()
    finally:
        if own:
            conn.close()


def get_state(key: str, default: Any = None) -> Any:
    with db() as conn:
        r = row(conn, "SELECT value FROM sync_state WHERE key=?", (key,))
    if not r:
        return default
    raw = r["value"]
    if isinstance(raw, str) and raw[:1] in "[{":
        return json_loads(raw, default)
    return raw


def log(level: str, scope: str, message: str, payload: Any = None) -> None:
    try:
        with db() as conn:
            conn.execute(
                "INSERT INTO event_log(ts, level, scope, message, payload) VALUES(?,?,?,?,?)",
                (utcnow(), level, scope, message, json_dumps(payload or {})),
            )
            # keep the log bounded
            conn.execute(
                "DELETE FROM event_log WHERE id < (SELECT MAX(id) - 4000 FROM event_log)"
            )
    except Exception:
        pass


def create_job(kind: str, message: str = "queued") -> str:
    job_id = new_id("job")
    with db() as conn:
        conn.execute(
            "INSERT INTO sync_jobs(id, kind, status, started_at, progress, message) VALUES(?,?,?,?,?,?)",
            (job_id, kind, "running", utcnow(), 0.0, message),
        )
    return job_id


def update_job(job_id: str, *, status: str | None = None, progress: float | None = None,
               message: str | None = None, stats: dict | None = None) -> None:
    sets, params = [], []
    if status is not None:
        sets.append("status=?")
        params.append(status)
    if progress is not None:
        sets.append("progress=?")
        params.append(max(0.0, min(1.0, progress)))
    if message is not None:
        sets.append("message=?")
        params.append(message)
    if stats is not None:
        sets.append("stats=?")
        params.append(json_dumps(stats))
    if status in ("completed", "failed", "cancelled"):
        sets.append("finished_at=?")
        params.append(utcnow())
    if not sets:
        return
    params.append(job_id)
    with db() as conn:
        conn.execute(f"UPDATE sync_jobs SET {', '.join(sets)} WHERE id=?", params)


